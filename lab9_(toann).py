class NetCDeep(nn.Module):

    def __init__(self, output_dim, input_dim=3):
        super(NetCDeep, self).__init__()
        self.dp_one = nn.Dropout(0.2)
        self.dp_two = nn.Dropout(0.2)

        self.bn_one1 = nn.BatchNorm2d(input_dim)
        self.bn_one2 = nn.BatchNorm2d(30)
        self.conv_one1 = nn.Conv2d(input_dim, 30, 3, padding=1)
        self.conv_one2 = nn.Conv2d(30, 30, 3)

        self.bn_two = nn.BatchNorm2d(30)
        self.conv_two1 = nn.Conv2d(30, 30, 3, padding=1)
        self.conv_two2 = nn.Conv2d(30, 30, 3, padding=1)
        self.conv_two3 = nn.Conv2d(30, 60, 3)

        self.bn_three = nn.BatchNorm2d(60)
        self.conv_three = nn.Conv2d(60, 120, 3)
        self.bn_four = nn.BatchNorm2d(120)

        self.fc1 = nn.Linear(120, 200)
        self.fc2 = nn.Linear(200, 60)
        self.out = nn.Linear(60, output_dim)

    def forward(self, x):
        x = self.bn_one1(x)
        x = self.conv_one1(x)
        x = F.relu(x)
        x = self.conv_one2(x)
        x = F.relu(x)
        x = self.bn_one2(x)
        x = F.max_pool2d(x, 2)

        x = self.bn_two(x)
        x3 = x
        x = self.conv_two1(x)
        x = F.relu(x)
        x = self.conv_two2(x)
        x = F.relu(x)
        x = x + x3
        x = self.conv_two3(x)
        x = F.relu(x)
        x = F.max_pool2d(x, 2)

        x = self.bn_three(x)
        x = self.conv_three(x)
        x = F.leaky_relu(x, 0.1)
        x = F.max_pool2d(x, 2)

        x = self.bn_four(x)
        x = x.view(x.size(0), -1)

        x = self.dp_one(x)
        x = self.fc1(x)
        x = F.relu(x)
        x = self.dp_two(x)
        x = self.fc2(x)
        x = F.relu(x)

        return self.out(x)

