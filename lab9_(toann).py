    def __init__(self, kernel_size):
        super(NetFashion, self).__init__()

        self.conv_one = nn.Conv2d(1, 30, kernel_size, padding=kernel_size // 2)
        self.conv_two = nn.Conv2d(30, 60, kernel_size, padding=kernel_size // 2)
        self.conv_three = nn.Conv2d(60, 120, kernel_size, padding=kernel_size // 2)

